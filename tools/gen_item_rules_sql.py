#!/usr/bin/env python3
"""Regenerate the item price rules migration from data/items.json + data/economy.json.
Run after changing item prices: python3 tools/gen_item_rules_sql.py, then `supabase db push`.
"""
import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
items = {k: v for k, v in json.loads((ROOT / "data/items.json").read_text()).items() if k != "_doc"}
trade = json.loads((ROOT / "data/economy.json").read_text())["trade"]
rows = ",\n  ".join(
    f"('{k}', {v['price']}, {max(1, math.floor(v['price'] * trade['min_mult']))}, {math.ceil(v['price'] * trade['max_mult'])})"
    for k, v in items.items())
out = ROOT / "backend/supabase/migrations/20261106000003_item_rules_seed.sql"
out.write_text(f"""-- GENERATED by tools/gen_item_rules_sql.py from data/items.json. Do not edit by hand.
insert into public.item_rules (item, base_price, min_price, max_price) values
  {rows}
on conflict (item) do update set base_price = excluded.base_price, min_price = excluded.min_price, max_price = excluded.max_price;
""")
print("wrote", out.relative_to(ROOT), len(items), "items")
